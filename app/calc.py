"""
Calculator functions
"""


def add(x: int, y: int) -> int:
    """Add two numbers.

    Args:
        x(int): first number
        y(int): second number

    Returns:
        int: sum of two numbers

    """
    return x + y


def subtract(x: int, y: int) -> int:
    """
    Subtract two numbers.

    Args:
        x(int): first number
        y(int): second number

    Returns:
        int: subtraction of two numbers
    """
    return y - x
